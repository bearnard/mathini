/**
 * Generates migrations/seeds/0008_questions_curated.sql: registers every Grade 6 curated bank question under its stable id
 * (= its qkey) with version 1 (ADR 0003 section 3). The code banks stay as the fallback and are not changed.
 *
 *   node --import tsx scripts/gen-question-seed.ts            write the seed file
 *   node --import tsx scripts/gen-question-seed.ts --check    exit 1 if the file on disk is not what the banks produce
 *
 * Deterministic (no timestamps in the file; created_at is stamped by SQLite when it runs) and idempotent when applied.
 * Only the Grade 6 registry (src/curriculum/grade6/reviewBanks.ts) is covered; other grades are not scheduled for review yet.
 * Diagram components cannot be serialised: such an item is stored with extra {"diagram":true} (the prompt/options/answer are kept).
 */
import fs from 'node:fs';
import { registerHooks } from 'node:module';
import { registerQuestionSql, questionIdFor, type SeedQuestion } from '../src/lib/server/questions/sql';

// Some topic modules import CSS; Node cannot, and the questions do not need it.
registerHooks({ resolve: (specifier, context, next) => (specifier.endsWith('.css') ? { url: 'data:text/javascript,export default {}', shortCircuit: true } : next(specifier, context)) });

const OUT = 'migrations/seeds/0008_questions_curated.sql';

export async function buildSeed(): Promise<{ sql: string; questions: number; duplicates: string[]; tasks: number }> {
  const { GRADE6_BANKS } = await import('../src/curriculum/grade6/reviewBanks');
  const lines: string[] = [
    '-- GENERATED by scripts/gen-question-seed.ts. Do not edit by hand (questionSeed.test.ts checks it is current).',
    '-- Registers every Grade 6 curated question: id = qkey of the prompt, version 1. Idempotent: safe to run twice.',
  ];
  const seen = new Set<string>();
  const duplicates: string[] = [];
  let count = 0;
  const tasks = Object.keys(GRADE6_BANKS).sort();
  for (const task of tasks) {
    const bank = await GRADE6_BANKS[task]();
    for (const item of bank) {
      const extra: Record<string, unknown> = {};
      if (item.hotspots) extra.hotspots = item.hotspots;
      if (item.image) extra.image = item.image;
      if (item.marks !== undefined) extra.marks = item.marks;
      if (item.paper) extra.paper = true;
      if (item.Diagram) extra.diagram = true;
      const q: SeedQuestion = {
        task, section: item.section ?? 'general', kind: item.kind ?? 'mcq', source: 'curated', prompt: item.prompt,
        options: item.options, answer: item.answer, explanation: item.explanation ?? '', extra, author: 'seed',
      };
      const id = questionIdFor(q);
      if (seen.has(id)) { duplicates.push(`${task}: ${item.prompt.slice(0, 60)}`); continue; }
      seen.add(id);
      lines.push(...registerQuestionSql(q));
      count++;
    }
  }
  return { sql: lines.join('\n') + '\n', questions: count, duplicates, tasks: tasks.length };
}

if (process.argv[1]?.endsWith('gen-question-seed.ts')) {
  const { sql, questions, duplicates, tasks } = await buildSeed();
  if (process.argv.includes('--check')) {
    const disk = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (disk !== sql) { console.error(`${OUT} is out of date: run node --import tsx scripts/gen-question-seed.ts`); process.exit(1); }
    console.log(`${OUT} is current (${questions} questions)`);
  } else {
    fs.writeFileSync(OUT, sql);
    console.log(`${questions} questions from ${tasks} tasks -> ${OUT} (${(sql.length / 1024).toFixed(0)} KiB)`);
  }
  if (duplicates.length) console.log(`skipped ${duplicates.length} duplicate (task, prompt) pair(s) inside the banks:\n  ${duplicates.join('\n  ')}`);
}
