// Regenerates src/curriculum/grade6/reviewBanks.ts: task slug -> lazy loader of that topic's exported `bank`.
// Run: node scripts/gen-review-registry.mjs   (reviewBanks.test.ts fails if the file is out of date)
import fs from 'node:fs';
import path from 'node:path';

const root = 'src/curriculum/grade6';
const found = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.tsx')) {
      const src = fs.readFileSync(p, 'utf8');
      if (!/^export const bank\b/m.test(src)) continue;
      const m = /\btask=(?:"([^"]+)"|\{['"]([^'"]+)['"]\})/.exec(src);
      if (m) found.push([m[1] ?? m[2], './' + path.relative(root, p).replace(/\.tsx$/, '').split(path.sep).join('/')]);
    }
  }
})(root);
found.sort((a, b) => (a[0] < b[0] ? -1 : 1));
const dup = found.map((f) => f[0]).filter((t, i, a) => a.indexOf(t) !== i);
if (dup.length) throw new Error('duplicate task slugs: ' + dup.join(', '));
const lines = [
  '// GENERATED by scripts/gen-review-registry.mjs. Do not edit by hand (reviewBanks.test.ts checks it is current).',
  "// Maps a Grade 6 task slug to a lazy loader for that topic's curated question bank, so the review screen",
  '// only downloads the topic modules it actually needs.',
  "import type { ReviewBankItem } from '../../lib/client/review/types';",
  '',
  'export const GRADE6_BANKS: Record<string, () => Promise<ReviewBankItem[]>> = {',
  ...found.map(([t, rel]) => `  '${t}': () => import('${rel}').then((m) => m.bank),`),
  '};',
  '',
];
fs.writeFileSync('src/curriculum/grade6/reviewBanks.ts', lines.join('\n'));
console.log(found.length + ' topics');
