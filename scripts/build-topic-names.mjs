#!/usr/bin/env node
// Builds src/components/admin/topicNames.generated.ts: task slug -> topic title and subject title,
// read from the curriculum registry (src/curriculum/gradeN/index.ts) and each topic component's
// `task="..."` / `apiPath="..."` props. The admin dashboard uses it so it can show
// "Earth & Moon Movement" instead of "earth-moon-movement".
//
//   node --import tsx scripts/build-topic-names.mjs           # write the file
//   node --import tsx scripts/build-topic-names.mjs --check   # exit 1 if the committed file is stale
//
// Re-run it whenever topics are added or renamed (a test fails if the file is stale).

import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const target = path.join(root, 'src', 'components', 'admin', 'topicNames.generated.ts');
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '');

const topics = {}; // `${grade}|${task}` -> [topic title, subject title]
const subjectsByGradeCode = {}; // `${grade}|${code}` -> subject title
const unmapped = [];

for (const n of [5, 6, 7, 8, 9, 10, 11, 12]) {
  const g = (await import(`${root}/src/curriculum/grade${n}/index.ts`))[`grade${n}`];
  const files = walk(path.join(root, 'src', 'curriculum', `grade${n}`)).filter((f) => f.endsWith('.tsx'));
  for (const s of g.subjects) {
    subjectsByGradeCode[`${g.id}|${s.id}`] = s.title;
    const firstWord = slug(String(s.title).split(/[ (]/)[0]);
    for (const t of s.terms) {
      for (const tp of t.topics) {
        const src = String(tp.component?._payload?._result ?? '');
        const spec = (src.match(/import\(['"]([^'"]+)['"]\)/) || [])[1];
        if (!spec) { unmapped.push(`${g.id}/${s.id}/${tp.id} (no import)`); continue; }
        const tail = spec.replace(/^\.\//, '');
        let cands = files.filter((f) => f.endsWith('/' + tail + '.tsx'));
        if (cands.length > 1) {
          // same relative path in two subjects (e.g. English and Afrikaans): prefer the one under this subject's folder
          const narrowed = cands.filter((f) => slug(path.relative(path.join(root, 'src', 'curriculum', `grade${n}`), f).split(path.sep)[0]).startsWith(firstWord.slice(0, 5)));
          if (narrowed.length === 1) cands = narrowed;
        }
        if (cands.length !== 1) { unmapped.push(`${g.id}/${s.id}/${tp.id} (${cands.length} files)`); continue; }
        const text = fs.readFileSync(cands[0], 'utf8');
        const task = (text.match(/\btask=\{?["'`]([^"'`]+)["'`]/) || [])[1];
        const api = (text.match(/\bapiPath=\{?["'`]\/api\/caps\/([a-z0-9-]+)["'`]/) || [])[1];
        if (api) subjectsByGradeCode[`${g.id}|${api}`] ??= s.title;
        if (!task) continue; // e.g. the mock-test entries have no task
        topics[`${g.id}|${task}`] = [tp.title, s.title];
      }
    }
  }
}

const sortObj = (o) => Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]));
const out = `// GENERATED by scripts/build-topic-names.mjs from the curriculum registry. Do not edit by hand.
// Re-run \`node --import tsx scripts/build-topic-names.mjs\` after adding or renaming topics.

/** "<grade>|<task slug>" -> [topic title, subject title] */
export const TOPIC_NAMES: Record<string, [string, string]> = ${JSON.stringify(sortObj(topics), null, 1)};

/** "<grade>|<subject code>" -> subject title. Codes are registry subject ids and the API path segment ("grade6", "eng", ...). */
export const SUBJECT_TITLES: Record<string, string> = ${JSON.stringify(sortObj(subjectsByGradeCode), null, 1)};
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== out) {
    console.error('topicNames.generated.ts is out of date. Run: node --import tsx scripts/build-topic-names.mjs');
    process.exit(1);
  }
  console.log(`OK: topicNames.generated.ts is up to date (${Object.keys(topics).length} topics).`);
} else {
  fs.writeFileSync(target, out);
  console.log(`Wrote ${path.relative(root, target)}: ${Object.keys(topics).length} topics, ${Object.keys(subjectsByGradeCode).length} subject codes, ${(out.length / 1024).toFixed(0)} KB. Unmapped registry topics: ${unmapped.length}.`);
  for (const u of unmapped.slice(0, 20)) console.log('  unmapped:', u);
}
