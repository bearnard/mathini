/**
 * One-off: register the active AI pool rows (item_cache, quality_score NULL or > 0) that are missing from `questions`, as dry-run SQL chunks you
 * apply by hand. Needed for rows the nightly top-up stored BEFORE registration at insert existed (they are not served from D1 until registered).
 * Reads an item_cache export; touches no database.
 *
 *   node --import tsx scripts/question-register-pool.ts [--items <json>] [--questions <json>] [--out <dir>] [--tag <name>] [--write]
 *
 * The export it expects (default name: <audit>/d1-serving/item_cache_unregistered.json; wrangler JSON, rows in [0].results):
 *   npx wrangler d1 execute preppals --remote --json --command "SELECT c.id, c.task, c.prompt, c.options, c.answer, c.explanation, c.section, c.quality_score FROM item_cache c LEFT JOIN questions q ON q.legacy_item_id = c.id WHERE q.id IS NULL AND (c.quality_score IS NULL OR c.quality_score > 0)"
 * (a few hundred rows, not the whole pool). If you also pass --questions (the questions export) the script double-checks every row against it.
 *
 * Every statement is idempotent (INSERT OR IGNORE / guarded), so applying a chunk twice does nothing, and a row identical to an existing question is LINKED to it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { backfillStatements, type PoolRowForIds } from '../src/lib/server/questions/backfill';
import { questionIdFor } from '../src/lib/server/questions/sql';

export const CHUNK_MAX = 1000;
export const NIGHT_CAP = 40000;
/** Rows written (indexes included): a new AI question 8 (question 4 with its legacy index, version 3, pointer 1); linking to an existing question 2; 1 per ledger row. */
export const COST = { newQuestion: 8, link: 2, ledger: 1 } as const;
const NOW = "CAST(strftime('%s', 'now') AS INTEGER) * 1000";
const q = (v: string) => `'${v.replace(/'/g, "''")}'`;

export interface ItemRow extends PoolRowForIds { quality_score?: number | null }
export interface KnownQuestion { id: string; legacy_item_id?: number | null }

export interface PoolChunk { name: string; rows: number; registered: number; linked: number; estimatedRows: number; sql: string }
export interface PoolPlan { chunks: PoolChunk[]; skipped: { itemId: number; why: string }[]; total: number }

export function planPoolRegistration(items: ItemRow[], known: KnownQuestion[] = [], tag = ''): PoolPlan {
  const skipped: PoolPlan['skipped'] = [];
  const byId = new Set(known.map((k) => k.id));
  const legacy = new Set(known.filter((k) => k.legacy_item_id != null).map((k) => Number(k.legacy_item_id)));
  const usable: ItemRow[] = [];
  for (const it of items) {
    if (it.quality_score != null && !(Number(it.quality_score) > 0)) { skipped.push({ itemId: it.id, why: 'quality_score 0 (rejected): never served' }); continue; }
    if (legacy.has(Number(it.id))) { skipped.push({ itemId: it.id, why: 'already registered (linked in questions)' }); continue; }
    usable.push(it);
  }
  const chunks: PoolChunk[] = [];
  for (let i = 0, n = 1; i < usable.length; i += CHUNK_MAX, n++) {
    const part = usable.slice(i, i + CHUNK_MAX);
    const { statements, registered, skipped: bad } = backfillStatements(part);
    for (const id of bad) skipped.push({ itemId: id, why: 'options are not valid JSON, or the same prompt appears twice in the chunk' });
    const linked = part.filter((p) => !bad.includes(p.id) && byId.has(questionIdFor({ task: p.task, prompt: p.prompt }))).length;
    const name = `register-pool${tag ? `-${tag}` : ''}-${String(n).padStart(3, '0')}`;
    const rows = (registered - linked) * COST.newQuestion + linked * COST.link + COST.ledger;
    const sql = [
      `-- ${name}: ${registered} pool rows (${linked} link to an existing question). Estimated rows written: ${rows}.`,
      '-- GENERATED by scripts/question-register-pool.ts. Idempotent: running it twice does nothing.',
      ...statements,
      `INSERT INTO migration_ledger (step, rows_written, ran_at, note) SELECT ${q(name)}, ${rows}, ${NOW}, 'estimate from scripts/question-register-pool.ts; compare with meta.rows_written' WHERE NOT EXISTS (SELECT 1 FROM migration_ledger WHERE step = ${q(name)});`,
    ].join('\n') + '\n';
    chunks.push({ name, rows: part.length, registered, linked, estimatedRows: rows, sql });
  }
  return { chunks, skipped, total: chunks.reduce((s, c) => s + c.estimatedRows, 0) };
}

const fmt = (n: number) => n.toLocaleString('en-ZA').replace(/,/g, ' ');

async function main() {
  const arg = (k: string, d: string) => { const i = process.argv.indexOf(k); return i >= 0 ? process.argv[i + 1] : d; };
  const dir = process.env.D1_AUDIT_DIR ?? path.join(process.env.HOME ?? '', 'Source/private/mathini/audit/d1-serving');
  const itemsFile = arg('--items', path.join(dir, 'item_cache_unregistered.json'));
  const qFile = arg('--questions', '');
  const out = arg('--out', path.join(dir, 'register-pool'));
  const tag = arg('--tag', '');
  if (!fs.existsSync(itemsFile)) {
    console.error(`Missing ${itemsFile}\nExport it with:\n  npx wrangler d1 execute preppals --remote --json --command "SELECT c.id, c.task, c.prompt, c.options, c.answer, c.explanation, c.section, c.quality_score FROM item_cache c LEFT JOIN questions q ON q.legacy_item_id = c.id WHERE q.id IS NULL AND (c.quality_score IS NULL OR c.quality_score > 0)" > ${itemsFile}`);
    process.exit(1);
  }
  const items = JSON.parse(fs.readFileSync(itemsFile, 'utf8'))[0].results as ItemRow[];
  const known = qFile ? (JSON.parse(fs.readFileSync(qFile, 'utf8'))[0].results as KnownQuestion[]) : [];
  const plan = planPoolRegistration(items, known, tag);
  const write = process.argv.includes('--write');
  const L = ['# Register unregistered AI pool rows', '', `Input: \`${path.resolve(itemsFile)}\` (${fmt(items.length)} rows)${qFile ? `, checked against \`${path.resolve(qFile)}\` (${fmt(known.length)} questions)` : ''}.`, `Mode: **${write ? 'WRITE' : 'DRY RUN (no files written; add --write)'}**.`, '', '| Chunk | Rows | New questions | Linked to an existing one | Estimated rows written |', '|---|---|---|---|---|'];
  for (const c of plan.chunks) L.push(`| ${c.name} | ${fmt(c.rows)} | ${fmt(c.registered - c.linked)} | ${fmt(c.linked)} | ${fmt(c.estimatedRows)} |`);
  L.push(`| **Total** | ${fmt(items.length)} | | | **${fmt(plan.total)}** |`, '', `Skipped: ${plan.skipped.length}${plan.skipped.length ? ` (${[...new Set(plan.skipped.map((s) => s.why))].join('; ')})` : ''}.`, `Estimate: ${COST.newQuestion} rows per new question, ${COST.link} per link, ${COST.ledger} per chunk ledger row. Calibrate on the first chunk with meta.rows_written. Nights at the ${fmt(NIGHT_CAP)}-row cap: ${Math.max(1, Math.ceil(plan.total / NIGHT_CAP))}.`, '', '## Apply', '', '```', 'npx wrangler d1 export preppals --remote --output <backup>.sql     # first', ...plan.chunks.map((c) => `npx wrangler d1 execute preppals --remote --file ${path.join(out, c.name + '.sql')} --json`), '```');
  const md = L.join('\n') + '\n';
  console.log(md);
  if (write) {
    fs.mkdirSync(out, { recursive: true });
    for (const c of plan.chunks) fs.writeFileSync(path.join(out, c.name + '.sql'), c.sql);
    fs.writeFileSync(path.join(out, 'plan.md'), md);
    console.log(`wrote ${plan.chunks.length} chunk file(s) to ${out}`);
  }
}

if (process.argv[1]?.endsWith('question-register-pool.ts')) await main();
