/**
 * Generates migrations/seeds/0023_g5_assessments.sql: registers the three Grade 5 Term 5 final assessments (Life Skills, History, Geography) as curated
 * multiple-choice questions, so the SERVER can find each question and mark the learner's answer itself (the browser's claim is never believed).
 *
 *   node --import tsx scripts/gen-g5-assessment-seed.ts            write the seed file
 *   node --import tsx scripts/gen-g5-assessment-seed.ts --check    exit 1 if the file on disk is not what the components produce
 *
 * Deterministic and idempotent (registerQuestionSql never overwrites a version that exists). The orchestrator applies it by hand, like the other seeds
 * (docs/notes/d1-sync.md). Until it is applied, these three assessments simply do not count (an answer the server cannot find is not credited).
 */
import fs from 'node:fs';
import { registerHooks } from 'node:module';
import { registerQuestionSql, type SeedQuestion } from '../src/lib/server/questions/sql';

registerHooks({ resolve: (specifier, context, next) => (specifier.endsWith('.css') ? { url: 'data:text/javascript,export default {}', shortCircuit: true } : next(specifier, context)) });

export const OUT = 'migrations/seeds/0023_g5_assessments.sql';

export async function buildSeed(): Promise<{ sql: string; questions: number }> {
  const mods = [
    await import('../src/curriculum/grade5/term5/life-skills/LifeSkillsAssessment'),
    await import('../src/curriculum/grade5/term5/history/FinalAssessment'),
    await import('../src/curriculum/grade5/term5/geography/GeographyAssessment'),
  ];
  const lines = [
    '-- GENERATED by scripts/gen-g5-assessment-seed.ts. Do not edit by hand (g5Assessments.test.ts checks it is current).',
    '-- Registers the Grade 5 Term 5 final assessment questions as curated multiple choice, so the server can mark answers. Idempotent: safe to run twice.',
  ];
  let count = 0;
  for (const { ASSESSMENT: a } of mods) {
    for (const q of a.questions) {
      const item: SeedQuestion = { task: a.task, section: a.section(q.id), kind: 'mcq', source: 'curated', prompt: q.text, options: q.options, answer: q.options[q.correctAnswer], explanation: q.explanation, extra: {}, author: 'seed' };
      lines.push(...registerQuestionSql(item));
      count += 1;
    }
  }
  return { sql: lines.join('\n') + '\n', questions: count };
}

async function main() {
  const { sql, questions } = await buildSeed();
  if (process.argv.includes('--check')) {
    const onDisk = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (onDisk !== sql) { console.error(`${OUT} is not current: run node --import tsx scripts/gen-g5-assessment-seed.ts`); process.exit(1); }
    console.log(`${OUT} is current (${questions} questions)`);
    return;
  }
  fs.writeFileSync(OUT, sql);
  console.log(`wrote ${OUT}: ${questions} questions`);
}
if (process.argv[1]?.endsWith('gen-g5-assessment-seed.ts')) void main();
