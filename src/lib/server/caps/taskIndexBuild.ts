// Pure builder for the generated task index: task slug -> [subject code, grade]. Used by scripts/build-task-index.ts to write
// taskIndex.generated.ts and by the freshness test, so the two can never disagree.
import type { SubjectConfig } from './types';

/** `topicNames` keys look like "<grade>|<task slug>" (src/components/admin/topicNames.generated.ts). */
export function buildTaskIndex(registry: Record<string, SubjectConfig>, topicNames: Record<string, unknown>): Record<string, [string, number]> {
  const out: Record<string, [string, number]> = {};
  const codes = Object.keys(registry);
  for (const key of Object.keys(topicNames).sort()) {
    const [g, slug] = key.split('|');
    const grade = Number(g);
    if (!slug || !Number.isFinite(grade)) continue;
    // Grade 6 slugs live under the legacy `grade6` code when it has them; otherwise the first subject code that does.
    const holders = codes.filter((c) => slug in registry[c].tasks);
    if (holders.length === 0) continue; // curated-only task: nothing to generate from
    const code = grade === 6 && holders.includes('grade6') ? 'grade6' : holders.find((c) => c !== 'grade6') ?? holders[0];
    out[slug] = [code, grade];
  }
  return out;
}

export function renderTaskIndexModule(index: Record<string, [string, number]>): string {
  const lines = Object.keys(index).sort().map((slug) => `  ${JSON.stringify(slug)}: [${JSON.stringify(index[slug][0])}, ${index[slug][1]}],`);
  return `// GENERATED by scripts/build-task-index.ts from the caps registry and the curriculum registry names. Do not edit by hand.
// Re-run \`node --import tsx scripts/build-task-index.ts\` after adding or renaming a task (taskIndex.test.ts checks it is current).
// slug -> [subject code in the caps registry, grade]. The weekly top-up needs it to write a proper prompt for any grade.

export const TASK_INDEX: Record<string, [code: string, grade: number]> = {
${lines.join('\n')}
};
`;
}
