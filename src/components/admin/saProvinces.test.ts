import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { SA_PROVINCES, SA_VIEWBOX, projectSA } from './saProvinces';

type Pt = [number, number];
function rings(d: string): Pt[][] {
  return d.split('Z').filter(Boolean).map((seg) => seg.replace(/^M/, '').split('L').map((p) => p.trim().split(' ').map(Number) as Pt));
}
// even-odd point-in-polygon over all rings of a province (holes such as Lesotho cancel out)
function inside(pt: Pt, rs: Pt[][]): boolean {
  let c = false;
  for (const r of rs) {
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i], [xj, yj] = r[j];
      if (yi > pt[1] !== yj > pt[1] && pt[0] < ((xj - xi) * (pt[1] - yi)) / (yj - yi) + xi) c = !c;
    }
  }
  return c;
}
const where = (lat: number, lon: number) => {
  const { x, y } = projectSA(lat, lon);
  return SA_PROVINCES.filter((p) => inside([x, y], rings(p.path))).map((p) => p.id);
};

test('there are nine provinces with valid, closed path data', () => {
  assert.equal(SA_PROVINCES.length, 9);
  for (const p of SA_PROVINCES) {
    assert.match(p.path, /^M[\d. L-]+Z/, p.id);
    assert.ok(rings(p.path).every((r) => r.length >= 4 && r.every(([x, y]) => Number.isFinite(x) && Number.isFinite(y))), p.id);
    assert.ok(p.cx > 0 && p.cx < SA_VIEWBOX.width && p.cy > 0 && p.cy < SA_VIEWBOX.height, `${p.id} label inside the map`);
  }
});
test('every coordinate sits inside the viewBox', () => {
  for (const p of SA_PROVINCES) for (const r of rings(p.path)) for (const [x, y] of r) {
    assert.ok(x >= -1 && x <= SA_VIEWBOX.width + 1 && y >= -1 && y <= SA_VIEWBOX.height + 1, `${p.id} ${x},${y}`);
  }
});
test('real city coordinates (exact) land in the right province: checks the data AND the projection', () => {
  const cities: [string, number, number, string][] = [
    ['Johannesburg', -26.2041, 28.0473, 'gauteng'], ['Pretoria', -25.7479, 28.2293, 'gauteng'], ['Soweto', -26.2678, 27.8585, 'gauteng'],
    ['Cape Town', -33.9249, 18.4241, 'western-cape'], ['Stellenbosch', -33.9321, 18.8602, 'western-cape'],
    ['Durban', -29.8587, 31.0218, 'kwazulu-natal'], ['Pietermaritzburg', -29.6006, 30.3794, 'kwazulu-natal'],
    ['Gqeberha', -33.9608, 25.6022, 'eastern-cape'], ['East London', -33.0153, 27.9116, 'eastern-cape'],
    ['Bloemfontein', -29.0852, 26.1596, 'free-state'], ['Polokwane', -23.9045, 29.4689, 'limpopo'],
    ['Mbombela', -25.4753, 30.9694, 'mpumalanga'], ['Kimberley', -28.7282, 24.7499, 'northern-cape'], ['Mahikeng', -25.8601, 25.6403, 'north-west'],
  ];
  for (const [name, lat, lon, want] of cities) assert.deepEqual(where(lat, lon), [want], name);
});
test('city positions rounded to 0.1 degree (what is stored) stay within ~5 map px of the land, so bubbles read as on the right coast', () => {
  const rounded: [string, number, number][] = [
    ['Cape Town', -33.9, 18.4], ['Durban', -29.9, 31.0], ['Gqeberha', -34.0, 25.6], ['East London', -33.0, 27.9], ['Stellenbosch', -33.9, 18.9],
    ['Johannesburg', -26.2, 28.0], ['Polokwane', -23.9, 29.5], ['Mbombela', -25.5, 30.9],
  ];
  const verts = SA_PROVINCES.flatMap((p) => rings(p.path).flat());
  for (const [name, lat, lon] of rounded) {
    const { x, y } = projectSA(lat, lon);
    const d = Math.min(...verts.map(([vx, vy]) => Math.hypot(vx - x, vy - y)));
    const isInside = where(lat, lon).length === 1;
    assert.ok(isInside || d <= 8, `${name} is ${d.toFixed(1)} px from the coast`);
  }
});
test('places outside South Africa are not inside any province, and Lesotho is a hole', () => {
  assert.deepEqual(where(51.5, -0.1), []); // London
  assert.deepEqual(where(-29.6, 28.2), []); // Maseru, Lesotho
});
test('north is up and east is right', () => {
  const jhb = projectSA(-26.2, 28.0), ct = projectSA(-33.9, 18.4), dbn = projectSA(-29.9, 31.0);
  assert.ok(jhb.y < ct.y);
  assert.ok(dbn.x > ct.x);
});
test('the committed file is small, attributed, and generated (not hand-edited)', () => {
  const src = fs.readFileSync(path.join(process.cwd(), 'src', 'components', 'admin', 'saProvinces.ts'), 'utf8');
  assert.ok(src.length < 25_000, `size ${src.length}`);
  assert.match(src, /GENERATED by scripts\/build-sa-provinces\.mjs/);
  assert.match(src, /Natural Earth/);
  assert.match(src, /PUBLIC DOMAIN/);
});
test('the source geojson is not committed to the repo', () => {
  const walk = (d: string): string[] => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.name === 'node_modules' || e.name === '.next' || e.name === '.git' || e.name === '.wrangler' ? [] : e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
  const big = walk(process.cwd()).filter((f) => /\.geojson$/.test(f) || /ne_10m_admin/.test(f));
  assert.deepEqual(big, []);
});
